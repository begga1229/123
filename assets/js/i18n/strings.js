  var i18n = {
    strings: { tr: tr, ru: ru, en: en },
    lang: 'tr',
    LANGS: ['tr', 'ru', 'en'],
    STORAGE_KEY: STORAGE_KEY
  };

  function interpolate(s, params) {
    if (!params) return s;
    return String(s).replace(/\{(\w+)\}/g, function (m, k) {
      return Object.prototype.hasOwnProperty.call(params, k) && params[k] != null ? String(params[k]) : m;
    });
  }

  /** Translate a key in the current language (falls back to en, then tr, then the key itself). */
  i18n.t = function (key, params) {
    var lang = i18n.lang;
    var table = i18n.strings[lang] || en;
    var s = table[key];
    if (s == null) s = en[key];
    if (s == null) s = tr[key];
    if (s == null) return key;
    return interpolate(s, params);
  };

  /** Translate in an explicit language without changing the current one. */
  i18n.tIn = function (lang, key, params) {
    var table = i18n.strings[lang] || en;
    var s = table[key] != null ? table[key] : (en[key] != null ? en[key] : (tr[key] != null ? tr[key] : key));
    return interpolate(s, params);
  };

  i18n.has = function (key) {
    return tr[key] != null || ru[key] != null || en[key] != null;
  };

  /** Pick a {tr,ru,en} object in the current language (delegates to EFS.util.pick when present). */
  i18n.pick = function (obj, lang) {
    lang = lang || i18n.lang;
    if (EFS.util && EFS.util.pick) return EFS.util.pick(obj, lang);
    if (obj == null) return '';
    if (typeof obj === 'string') return obj;
    return obj[lang] || obj.en || obj.tr || obj.ru || '';
  };

  /** Set the UI language, persist it and update <html lang>. Returns the language actually set. */
  i18n.setLang = function (lang) {
    if (i18n.LANGS.indexOf(lang) < 0) lang = 'tr';
    i18n.lang = lang;
    try { if (root.localStorage) root.localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* storage blocked */ }
    try { if (root.document && root.document.documentElement) root.document.documentElement.setAttribute('lang', lang); } catch (e2) { /* no DOM */ }
    return lang;
  };

  /** Detect the language: persisted value first, then navigator.language (ru → ru, en → en, else tr). */
  i18n.detect = function () {
    var stored = null;
    try { if (root.localStorage) stored = root.localStorage.getItem(STORAGE_KEY); } catch (e) { stored = null; }
    if (stored && i18n.LANGS.indexOf(stored) >= 0) return stored;
    var nav = '';
    try {
      var n = root.navigator;
      nav = (n && (n.language || (n.languages && n.languages[0]))) || '';
    } catch (e2) { nav = ''; }
    nav = String(nav).toLowerCase();
    if (nav.indexOf('ru') === 0) return 'ru';
    if (nav.indexOf('en') === 0) return 'en';
    return 'tr';
  };

  /** Count of keys (used by self-tests). */
  i18n.keyCount = function () { return Object.keys(tr).length; };

  /** Keys that are missing in any language (used by self-tests). */
  i18n.missingKeys = function () {
    var all = {}, out = [];
    [tr, ru, en].forEach(function (tbl) { Object.keys(tbl).forEach(function (k) { all[k] = 1; }); });
    Object.keys(all).forEach(function (k) {
      if (tr[k] == null) out.push('tr:' + k);
      if (ru[k] == null) out.push('ru:' + k);
      if (en[k] == null) out.push('en:' + k);
    });
    return out;
  };

  EFS.i18n = i18n;
  return i18n;
